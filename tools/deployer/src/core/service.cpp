  unit += "Documentation=https://github.com/" + std::string(kRepoSlug) + "\n";
  unit += "After=network-online.target\n";
  unit += "Wants=network-online.target\n";
  unit += "\n[Service]\n";
  unit += "Type=simple\n";
  unit += "WorkingDirectory=" + systemdQuoted(appDirOf(options)) + "\n";
  unit += "EnvironmentFile=-" + systemdQuoted(envFileOf(options)) + "\n";
  unit += systemdEnvironment("PORT", std::to_string(options.port)) + "\n";
  unit += systemdEnvironment("HOST", hostOf(options)) + "\n";
  unit += systemdEnvironment("NODE_ENV", nodeEnvOf(options)) + "\n";
  unit += systemdEnvironment("DATA_DIR", dataDirOf(options)) + "\n";
  unit += "ExecStart=" + systemdQuoted(execPath) + " " +
          systemdQuoted(launchEntryOf(options)) + "\n";
