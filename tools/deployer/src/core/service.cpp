// cmd 批处理：值里 % 需要写成 %% 才不会在运行时被展开；路径本身不允许 "。
std::string cmdText(const std::string& value) {
  std::string out;
  out.reserve(value.size() + 4);
  for (char ch : value) {
    if (ch == '%') {
      out += "%%";
      continue;
    }
    if (ch == '"' || ch == '\r' || ch == '\n') continue;
    out.push_back(ch);
  }
  return out;
}

// systemd 单元里双引号包裹的参数：转义 \ 与 "；% 是单元说明符、$ 会触发变量展开。
std::string systemdQuoted(const std::string& value) {
  std::string out = "\"";
  for (char ch : value) {
    if (ch == '%' || ch == '$') {
      out.push_back(ch);
      out.push_back(ch);
    } else if (ch == '\\' || ch == '"') {
      out.push_back('\\');
      out.push_back(ch);
    } else if (ch == '\r' || ch == '\n') {
      continue;
    } else {
      out.push_back(ch);
    }
  }
  out.push_back('"');
  return out;
}

// systemd 的 Environment= 赋值：含空白或特殊字符时整体加引号。
std::string systemdEnvironment(const std::string& key, const std::string& value) {
  bool needsQuote = value.empty();
  for (char ch : value) {
    if (ch == ' ' || ch == '\t' || ch == '"' || ch == '\'' || ch == '\\' ||
        ch == '%' || ch == '$' || ch == ';' || ch == '#') {
      needsQuote = true;
      break;
    }
  }
  if (!needsQuote) return "Environment=" + key + "=" + value;
  std::string escaped;
  for (char ch : value) {
    if (ch == '%' || ch == '$') {
      escaped.push_back(ch);
      escaped.push_back(ch);
    } else if (ch == '\\' || ch == '"') {
      escaped.push_back('\\');
      escaped.push_back(ch);
    } else if (ch == '\r' || ch == '\n') {
      continue;
    } else {
      escaped.push_back(ch);
    }
  }
  return "Environment=\"" + key + "=" + escaped + "\"";
}

// POSIX shell 单引号字符串。
std::string shQuoted(const std::string& value) {
  std::string out = "'";
  for (char ch : value) {
    if (ch == '\'')
      out += "'\\''";
    else if (ch != '\r' && ch != '\n')
      out.push_back(ch);
  }
  out.push_back('\'');
  return out;
}

// launchd 的 sh -c 脚本片段。
std::string launchdShellScript(const Options& options, const std::string& execPath) {
  std::string script;
  script += "set -a; . " + shQuoted(envFileOf(options)) + "; set +a; ";
  script += "exec " + shQuoted(execPath) + " " + shQuoted(launchEntryOf(options));
  script += " >> " + shQuoted(serverLogOf(options)) + " 2>&1";
  return script;
}

bool startsWith(const std::string& text, const char* prefix) {
  return text.rfind(prefix, 0) == 0;
}

bool parseBoolValue(const std::string& value, bool& out) {
  if (value == "1" || value == "true" || value == "yes") {
    out = true;
    return true;
  }
  if (value == "0" || value == "false" || value == "no") {
    out = false;
    return true;
  }
  return false;
}

bool parseIntValue(const std::string& value, int& out) {
  if (value.empty()) return false;
  int result = 0;
  for (char ch : value) {
    if (ch < '0' || ch > '9') return false;
    result = result * 10 + (ch - '0');
    if (result > 1000000) return false;
  }
  out = result;
  return true;
}

