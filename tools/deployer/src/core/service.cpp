std::string windowsStartScript(const Options& options) {
  std::string script;
  script += "@echo off\r\n";
  // 批处理按控制台代码页解析；切到 UTF-8 后中文提示与 UTF-8 的 .env 才可读。
  script += "chcp 65001 >nul\r\n";
  script += "rem ============================================================\r\n";
  script += "rem  MES Homework start script (generated by deployer)\r\n";
  script += "rem  Generated at: " + isoNow() + "\r\n";
  script += "rem  Do not edit; reinstall/repair will overwrite this file.\r\n";
  script += "rem ============================================================\r\n";
  script += "setlocal\r\n";
  // 用脚本自身位置推导安装目录，避免批处理里出现非 ASCII 路径。
  script += "set \"INSTALL=%~dp0\"\r\n";
  script += "set \"PORT=" + cmdText(std::to_string(options.port)) + "\"\r\n";
  script += "set \"HOST=" + cmdText(hostOf(options)) + "\"\r\n";
  script += "set \"NODE_ENV=" + cmdText(nodeEnvOf(options)) + "\"\r\n";
  script += "rem APP_SECRET / DATA_DIR are loaded from .env via Node --env-file.\r\n";
  script += "if not exist \"%INSTALL%logs\" mkdir \"%INSTALL%logs\" >nul 2>&1\r\n";
  script += "cd /d \"%INSTALL%app\"\r\n";
  script += "set \"ENTRY=%INSTALL%app\\server\\index.mjs\"\r\n";
  script += "if exist \"%INSTALL%app\\tools\\ops\\supervise.mjs\" set \"ENTRY=%INSTALL%app\\tools\\ops\\supervise.mjs\"\r\n";
  script += "\"%INSTALL%runtime\\node.exe\" --env-file=\"%INSTALL%.env\" "
            "\"%ENTRY%\" >> \"%INSTALL%logs\\server.log\" 2>&1\r\n";
  script += "exit /b %errorlevel%\r\n";
  return script;
}

std::string windowsServerTaskCommand(const Options& options) {
  const std::string script =
      mes::platform::joinPath(installDirOf(options), "start.cmd");
  // 该命令用于展示/手动排障；实际安装由 engine 通过任务 XML 完成（可设置无限运行时长）。
  return "schtasks /Create /TN \"" + std::string(kTaskName) +
         "\" /SC ONSTART /RU SYSTEM /RL HIGHEST /TR \"cmd.exe /c \\\"" + script +
         "\\\"\" /F";
}

