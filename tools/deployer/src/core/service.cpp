std::string xmlEscape(const std::string& text) {
  std::string out;
  out.reserve(text.size() + 8);
  for (char ch : text) {
    switch (ch) {
      case '&': out += "&amp;"; break;
      case '<': out += "&lt;"; break;
      case '>': out += "&gt;"; break;
      case '"': out += "&quot;"; break;
      case '\'': out += "&apos;"; break;
      case '\r': case '\n': break;
      default: out.push_back(ch); break;
    }
  }
  return out;
}

std::string utf16LeWithBom(const std::string& utf8) {
  std::string out;
  out.push_back(static_cast<char>(0xFF));
  out.push_back(static_cast<char>(0xFE));
  size_t index = 0;
  while (index < utf8.size()) {
    const unsigned char lead = static_cast<unsigned char>(utf8[index]);
    uint32_t codePoint = 0;
    size_t length = 0;
    if (lead < 0x80) {
      codePoint = lead;
      length = 1;
    } else if ((lead & 0xE0) == 0xC0) {
      codePoint = lead & 0x1Fu;
      length = 2;
    } else if ((lead & 0xF0) == 0xE0) {
      codePoint = lead & 0x0Fu;
      length = 3;
    } else if ((lead & 0xF8) == 0xF0) {
      codePoint = lead & 0x07u;
      length = 4;
    } else {
      // 非法字节：替换为 U+FFFD，保证 XML 仍是合法 Unicode。
      codePoint = 0xFFFD;
      length = 1;
    }
    if (index + length > utf8.size()) {
      codePoint = 0xFFFD;
      length = 1;
    } else {
      for (size_t i = 1; i < length; ++i) {
        const unsigned char continuation =
            static_cast<unsigned char>(utf8[index + i]);
        if ((continuation & 0xC0) != 0x80) {
          codePoint = 0xFFFD;
          length = 1;
          break;
        }
        codePoint = (codePoint << 6) | (continuation & 0x3Fu);
      }
    }
    index += length;
    auto pushUnit = [&out](uint16_t unit) {
      out.push_back(static_cast<char>(unit & 0xFF));
      out.push_back(static_cast<char>((unit >> 8) & 0xFF));
    };
    if (codePoint <= 0xFFFF) {
      pushUnit(static_cast<uint16_t>(codePoint));
    } else {
      const uint32_t adjusted = codePoint - 0x10000;
      pushUnit(static_cast<uint16_t>(0xD800 + (adjusted >> 10)));
      pushUnit(static_cast<uint16_t>(0xDC00 + (adjusted & 0x3FF)));
    }
  }
  return out;
}

// ---------------------------------------------------------------- 提权参数编解码
bool isSupportedElevatedAction(const std::string& action) {
  return action == "service-install" || action == "service-remove" ||
         action == "service-start" || action == "service-stop" ||
         action == "firewall-open" || action == "service-query";
}

std::vector<std::string> elevatedActionArgs(const std::string& action,
                                            const Options& options) {
  std::vector<std::string> args;
  args.push_back("--elevated-action=" + action);
  args.push_back("--install-dir=" + installDirOf(options));
  args.push_back("--data-dir=" + dataDirOf(options));
  args.push_back("--port=" + std::to_string(options.port));
  args.push_back(std::string("--edition=") +
                 (options.edition == Edition::Server ? "server" : "local"));
  args.push_back(std::string("--node-env=") +
                 (options.production ? "production" : "development"));
  if (options.lan) args.push_back("--lan=1");
  if (options.autostart) args.push_back("--autostart=1");
  if (options.firewall) args.push_back("--firewall=1");
  if (!options.releaseTag.empty())
    args.push_back("--release-tag=" + options.releaseTag);
  return args;
}

bool parseElevatedActionArgs(const std::vector<std::string>& args,
                             std::string& action, Options& options,
                             std::string& error) {
  action.clear();
  options = Options{};
  std::string edition;
  for (const std::string& arg : args) {
    if (startsWith(arg, "--elevated-action=")) {
      action = arg.substr(std::string("--elevated-action=").size());
    } else if (startsWith(arg, "--install-dir=")) {
      options.installDir = arg.substr(std::string("--install-dir=").size());
    } else if (startsWith(arg, "--data-dir=")) {
      options.dataDir = arg.substr(std::string("--data-dir=").size());
    } else if (startsWith(arg, "--port=")) {
      int port = 0;
      if (!parseIntValue(arg.substr(std::string("--port=").size()), port)) {
        error = "提权参数中的端口无效：" + arg;
        return false;
      }
      options.port = port;
    } else if (startsWith(arg, "--edition=")) {
      edition = arg.substr(std::string("--edition=").size());
    } else if (startsWith(arg, "--node-env=")) {
      options.production =
          arg.substr(std::string("--node-env=").size()) == "production";
    } else if (startsWith(arg, "--lan=")) {
      if (!parseBoolValue(arg.substr(std::string("--lan=").size()), options.lan)) {
        error = "提权参数中的 --lan 无效";
        return false;
      }
    } else if (startsWith(arg, "--autostart=")) {
      if (!parseBoolValue(arg.substr(std::string("--autostart=").size()),
                          options.autostart)) {
        error = "提权参数中的 --autostart 无效";
        return false;
      }
    } else if (startsWith(arg, "--firewall=")) {
      if (!parseBoolValue(arg.substr(std::string("--firewall=").size()),
                          options.firewall)) {
        error = "提权参数中的 --firewall 无效";
        return false;
      }
    } else if (startsWith(arg, "--release-tag=")) {
      options.releaseTag = arg.substr(std::string("--release-tag=").size());
    }
  }
  if (edition == "server")
    options.edition = Edition::Server;
  else if (edition == "local")
    options.edition = Edition::Local;
  else {
    error = "提权参数缺少有效的 --edition=local|server";
    return false;
  }
  if (!isSupportedElevatedAction(action)) {
    error = "不支持的提权动作：" + action;
    return false;
  }
  if (options.installDir.empty()) {
    error = "提权参数缺少 --install-dir";
    return false;
  }
  if (!isAbsolutePath(options.installDir)) {
    error = "提权参数中的安装目录必须是绝对路径：" + options.installDir;
    return false;
  }
  if (options.port < 1 || options.port > 65535) {
    error = "提权参数中的端口需在 1-65535 之间";
    return false;
  }
  if (options.dataDir.empty()) options.dataDir = dataDirOf(options);
  return true;
}

